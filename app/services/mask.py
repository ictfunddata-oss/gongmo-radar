"""화면에 보여 줄 본문에서 담당자 연락처를 가린다(개인정보 최소화)."""
import re

# 로컬 부분은 ASCII만 본다. \w(한글 포함)로 두면 공백 없는 긴 글에서 시작 위치마다 되짚어 O(n²)으로 느려진다.
# 앞 글자가 로컬 부분 글자가 아닐 때만 시작해(뒤돌아보기) 한 단어를 한 번만 본다
_EMAIL = re.compile(r"(?<![A-Za-z0-9._%+-])[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
# 국내(0으로 시작)·국제(+국가번호) 형식만 잡는다 — '제 2026-0977 호' 같은 공고번호는 건드리지 않음
_PHONE = re.compile(r"(?<![\d-])(?:\+\d{1,3}[\s.-]?\d{1,3}|\(?0\d{1,2}\)?)[\s.-]?\d{3,4}[\s.-]?\d{4}(?!\d)")


def mask_contacts(text):
    """담당자 이메일·전화번호를 가린다."""
    return _PHONE.sub("[전화번호]", _EMAIL.sub("[이메일]", text or ""))
